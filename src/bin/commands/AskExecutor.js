import fs from "node:fs";
import path from "path";
import Prompt, { PromptError } from "../../lib/Prompt.js";
import { readFile, asJson } from "../../lib/util/FileUtils.js";
import { readStdIn } from "../../lib/util/Input.js";
import { resolveFromConfig } from "../../lib/ModelResolver.js";
import { loadSkillsCatalog } from "../../lib/Skills.js";
import { Policy } from "../../lib/Policy.js";
import { BUDGET_EXIT_CODE } from "../../lib/LoopBudget.js";
import { LockError, LOCK_EXIT_CODE, parseDuration } from "../../lib/HistoryLock.js";
import { PENDING_EXIT_CODE } from "../../lib/HumanInLoop.js";
import { createEventStream } from "../../lib/Events.js";

export async function askExecutor(params) {
  // Structured JSON event stream for a supervising process. Default OFF: an empty
  // --events value yields a disabled (no-op) stream. Created before anything that can
  // throw (e.g. the history lock) so run.start/run.end bracket the whole run.
  const events = createEventStream(params.events, { runId: params.runId || undefined });
  let runStatus = "ok";
  try {
    const baseInstructions = params.baseInstructions;
    const instructions = params.instructions;
    const model = params.useModel
      ? resolveFromConfig({ models: params.models, model: params.model }, params.useModel)
      : (params.models && Object.keys(params.models).length > 0
        ? resolveFromConfig({ models: params.models, model: params.model })
        : params.model);
    const question = params.question;
    const role = params.role;
    const history = params.history;
    const outputSchema = params.outputSchema;
    const context = params.context;
    const storage = params.storage;
    const stream = params.stream;
    const autoCompact = params.autoCompact === true || params.autoCompact === "true";
    const compaction = autoCompact ? params.compaction : null;

    // Loop budget: an always-on iteration cap plus optional token/time caps. The
    // simple --maxIterations flag sets the iteration cap; the --budget object
    // (config key) can override it and add maxTokens/maxTimeMs. Values from the
    // budget object take precedence over the flag.
    const budgetSpec = (params.budget && typeof params.budget === "object") ? params.budget : {};
    const maxIterationsFlag =
      params.maxIterations !== undefined && params.maxIterations !== null && `${params.maxIterations}` !== ""
        ? parseInt(params.maxIterations, 10)
        : null;
    const budget = {
      maxIterations:
        budgetSpec.maxIterations !== undefined && budgetSpec.maxIterations !== null
          ? parseInt(budgetSpec.maxIterations, 10)
          : (maxIterationsFlag !== null ? maxIterationsFlag : 50),
      maxTokens:
        budgetSpec.maxTokens !== undefined && budgetSpec.maxTokens !== null
          ? parseInt(budgetSpec.maxTokens, 10)
          : null,
      maxTimeMs:
        budgetSpec.maxTimeMs !== undefined && budgetSpec.maxTimeMs !== null
          ? parseInt(budgetSpec.maxTimeMs, 10)
          : null
    };

    // Session lock config. --waitLock <duration> (empty = fail fast) opts into
    // poll-waiting for a busy history lock; --staleLock <duration> overrides the
    // threshold past which an un-refreshed lock is stolen (default 30m). Durations
    // accept ms/s/m/h suffixes or a bare number of milliseconds.
    const waitMs = parseDuration(params.waitLock);
    const staleMs = params.staleLock !== undefined && params.staleLock !== null && `${params.staleLock}` !== ""
      ? parseDuration(params.staleLock)
      : undefined;
    const lock = {
      waitMs: waitMs !== null ? waitMs : 0,
      staleMs
    };

    const bio = params.bio;
    const permissions = params.permissions;
    const references = params.references || (params.packageDir ? path.join(params.packageDir, "references") : "");
    const skills = params.skills || "skills";

    // Optional policy guardrails. An inline policy object (aux4 delivers a config.yaml
    // object param as a JSON string for free, parsed upstream). Absent => no policy =>
    // unchanged. runId is auto-generated by Policy when not provided.
    let policy = null;
    const policySpec = params.policy;
    const hasPolicy =
      policySpec && typeof policySpec === "object" && Object.keys(policySpec).length > 0;
    if (hasPolicy) {
      policy = Policy.load(policySpec, {
        staticPermissions: permissions,
        agent: (bio && bio.name) || "agent",
        runId: params.runId || undefined,
        costs: params.costs || {},
        escalationOptions: params.escalationWaitMs ? { waitMs: parseInt(params.escalationWaitMs) } : {}
      });
    }

    // AGENTS.md fallback: try AGENTS.md → AGENT.md → instructions.md
    let instructionsFile = instructions;
    if (instructionsFile === "AGENTS.md" && !fs.existsSync("AGENTS.md")) {
      if (fs.existsSync("AGENT.md")) {
        instructionsFile = "AGENT.md";
      } else if (fs.existsSync("instructions.md")) {
        instructionsFile = "instructions.md";
      }
    }

    let contextContent;
    if (context === true || context === "true") {
      contextContent = await readStdIn();
    }

    let message = question;
    if (contextContent) {
      message = `---\n${contextContent}\n---\n${question}`;
    }

    // Human-in-the-loop mode. "park" (default) suspends on no-TTY askUser / permission
    // ask so the question can be surfaced and answered later; "auto" keeps the legacy
    // auto-proceed / auto-deny behavior. Parking needs a history file to persist against,
    // so with no history it always falls back to "auto".
    const humanInLoopMode = (params.humanInLoop === "auto") ? "auto" : "park";
    const canPark = history && history !== "";

    // Create tools configuration
    const toolsConfig = storage ? { storage } : {};
    if (permissions && typeof permissions === "object" && Object.keys(permissions).length > 0) {
      toolsConfig.permissions = permissions;
    }
    if (references) {
      toolsConfig.references = references;
    }
    if (skills) {
      toolsConfig.skills = skills;
    }
    toolsConfig.humanInLoop = canPark ? humanInLoopMode : "auto";

    const prompt = new Prompt(model, toolsConfig, { compaction, policy, budget, lock, events });
    await prompt.init();

    // Announce the run. Model id + a truncated goal give a supervisor enough context
    // without leaking the full prompt into the event log.
    events.emit("run.start", {
      agent: (bio && bio.name) || "agent",
      model: prompt.modelId,
      apiType: prompt.apiType,
      goal: typeof question === "string" ? question.slice(0, 200) : ""
    });

    if (bio && typeof bio === "object" && Object.keys(bio).length > 0) {
      const bioParts = [];
      if (bio.name) bioParts.push(`**Name:** ${bio.name}`);
      if (bio.role) bioParts.push(`**Role:** ${bio.role}`);
      if (bio.description) bioParts.push(`**Description:** ${bio.description}`);
      if (bioParts.length > 0) {
        await prompt.instructions(`# Agent Identity\n\n${bioParts.join("\n")}`);
      }
    }

    if (baseInstructions) {
      await prompt.instructions(await readFile(baseInstructions), params);
    }
    if (instructionsFile) {
      await prompt.instructions(await readFile(instructionsFile), params);
    }

    const skillsCatalog = loadSkillsCatalog(skills);
    if (skillsCatalog) {
      await prompt.instructions(skillsCatalog);
    }

    await prompt.instructions("If you need to ask the user a question or need clarification, use the askUser tool. Always call askUser alone, never in parallel with other tools.");

    await prompt.history(history);

    if (stream === true || stream === "true") {
      prompt.setStreaming(true);
      prompt.onToken(token => process.stdout.write(token));
      prompt.onMessage(answer => {
        process.stdout.write("\n");
      });
    } else {
      prompt.onMessage(answer => {
        console.log(answer.trim());
      });
    }

    prompt.setOutputSchema(await readFile(outputSchema).then(asJson()));

    if (prompt.pendingQuestion) {
      // The history has a parked question. Resolve it: an explicit --answer wins,
      // otherwise the incoming question IS the answer (the user's reply).
      const explicitAnswer = (params.answer !== undefined && params.answer !== "") ? params.answer : null;
      const answerText = explicitAnswer !== null ? explicitAnswer : question;

      if (answerText === undefined || answerText === "") {
        // Nothing to answer with — stay parked and remind the supervisor.
        prompt.reemitPending();
      } else {
        await prompt.resolvePending(answerText);
        // If --answer was used AND a distinct new question was also supplied, run it now.
        if (explicitAnswer !== null && question && question !== explicitAnswer && !prompt.paused) {
          await prompt.message(message, params, role);
        }
      }
    } else {
      await prompt.message(message, params, role);
    }

    if (prompt.paused) {
      process.exitCode = PENDING_EXIT_CODE;
      runStatus = "parked";
    }

    prompt.close();

    // A tripped loop budget is not a crash: the answer (budget-exceeded note) has
    // already been emitted and the history persisted. Surface a distinguishable
    // non-zero exit so a supervisor can detect the truncation.
    if (prompt.budgetExceeded) {
      process.exitCode = BUDGET_EXIT_CODE;
      runStatus = "budget-exceeded";
    }

    // Final run event with the terminal status and total token usage. Statuses:
    // ok | budget-exceeded | parked | lock-failed | error.
    events.emit("run.end", { status: runStatus, tokens: prompt.tokenUsage });
    events.close();
  } catch (error) {
    // Contention on the history lock is an expected, recoverable condition — not a
    // crash. Report it cleanly (no stack trace) and exit with the distinct lock code
    // so a supervisor can tell "history in use" apart from a real failure.
    if (error instanceof LockError) {
      events.emit("run.end", { status: "lock-failed", error: error.message });
      events.close();
      console.error(`Error: ${error.message}`);
      process.exit(LOCK_EXIT_CODE);
    }
    events.emit("run.end", { status: "error", error: error.message });
    events.close();
    if (error instanceof PromptError) {
      console.error("Prompt error:", error.message);
    } else {
      console.error("Error in askExecutor:");
      console.error("Message:", error.message);
      console.error("Stack trace:");
      console.error(error.stack);
    }
    throw error;
  }
}
